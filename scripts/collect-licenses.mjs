import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const notices = [];
const seenPackages = new Set();
const licenseName = /^(licen[cs]e|copying|notice)(?:[._-].*)?$/i;

async function entries(directory) {
  try { return await fs.readdir(directory, { withFileTypes: true }); }
  catch (error) { if (error.code === 'ENOENT') return []; throw error; }
}
async function addFile(label, file) {
  const content = (await fs.readFile(file, 'utf8')).replace(/\r\n/g, '\n').trim();
  if (content) notices.push({ label, content });
}
async function collectPackage(directory, label) {
  for (const item of await entries(directory)) {
    if (item.isFile() && licenseName.test(item.name)) await addFile(`${label} — ${item.name}`, path.join(directory, item.name));
    if (item.isDirectory() && /^licen[cs]es$/i.test(item.name)) {
      for (const child of await entries(path.join(directory, item.name))) {
        if (child.isFile() && /\.(?:txt|md|html)$/i.test(child.name)) {
          await addFile(`${label} — ${item.name}/${child.name}`, path.join(directory, item.name, child.name));
        }
      }
    }
  }
}
async function collectNpm(directory) {
  for (const item of await entries(directory)) {
    if (!item.isDirectory() || item.name.startsWith('.')) continue;
    const location = path.join(directory, item.name);
    if (item.name.startsWith('@')) { await collectNpm(location); continue; }
    let metadata;
    try { metadata = JSON.parse(await fs.readFile(path.join(location, 'package.json'), 'utf8')); }
    catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    const label = `npm: ${metadata.name}@${metadata.version}`;
    if (!seenPackages.has(label)) {
      seenPackages.add(label);
      await collectPackage(location, label);
    }
    await collectNpm(path.join(location, 'node_modules'));
  }
}

await collectNpm(path.join(root, 'node_modules'));
const registry = path.join(root, '.cache', 'cargo', 'registry', 'src');
for (const index of await entries(registry)) {
  if (!index.isDirectory()) continue;
  for (const crate of await entries(path.join(registry, index.name))) {
    if (crate.isDirectory()) await collectPackage(path.join(registry, index.name, crate.name), `Cargo: ${crate.name}`);
  }
}

const runtimeNotice = path.join(root, '.tools', 'w64devkit', 'COPYING.MinGW-w64-runtime.txt');
try { await addFile('MinGW-w64 linked Windows runtime', runtimeNotice); }
catch (error) { if (error.code !== 'ENOENT') throw error; }
const rustNoticeRoot = path.join(root, '.tools', 'rust', 'share', 'doc', 'rust');
await collectPackage(rustNoticeRoot, 'Rust standard library and distributed support libraries');

notices.sort((a, b) => a.label.localeCompare(b.label, 'en'));
const header = [
  'RepoTower — third-party license texts',
  '',
  'Generated by scripts/collect-licenses.mjs from locally installed dependencies.',
  'This intentionally includes development dependencies as well as bundled runtime',
  'dependencies so that nested package notices are retained. Inclusion here does not',
  'mean a development tool is distributed in the portable application.',
  'Electron and Chromium additionally retain LICENSE.electron.txt and LICENSES.chromium.html',
  'beside the portable executable. Package and Cargo lockfiles record exact versions.',
  '',
].join('\n');
await fs.writeFile(path.join(root, 'THIRD_PARTY_LICENSES.txt'), header + notices.map(({ label, content }) =>
  `\n${'='.repeat(80)}\n${label}\n${'='.repeat(80)}\n\n${content}\n`).join(''), 'utf8');
console.log(`Collected ${notices.length} third-party license texts.`);
